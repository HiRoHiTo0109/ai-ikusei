HEAD = (
    "def train_head(F, y, n=2):\n"
    "    # 判断係：特徴の表 F から答えを当てる係を学習して返す（Lv11 の多分類版）\n"
    "    F = np.asarray(F, dtype=float)\n"
    "    mu, sd = F.mean(axis=0), F.std(axis=0) + 1e-6      # 特徴の大きさをそろえる\n"
    "    Z = (F - mu) / sd\n"
    "    W = np.zeros((Z.shape[1], n)); b = np.zeros(n); Y = np.eye(n)[y]\n"
    "    for _ in range(500):\n"
    "        z = Z @ W + b\n"
    "        p = np.exp(z - z.max(axis=1, keepdims=True)); p /= p.sum(axis=1, keepdims=True)\n"
    "        d = (p - Y) / len(Z)\n"
    "        W -= 0.5 * Z.T @ d; b -= 0.5 * d.sum(axis=0)\n"
    "    return lambda G: np.argmax(((np.asarray(G, dtype=float) - mu) / sd) @ W + b, axis=1)\n\n"
)

