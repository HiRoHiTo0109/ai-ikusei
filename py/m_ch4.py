    "def conv2d(img, kernel):\n"
    "    # Lv22 で作った畳み込みの「速い版」（やっていることは同じ）\n"
    "    return np.einsum(\"ijkl,kl->ij\", sliding_window_view(img, kernel.shape), kernel)\n\n"
