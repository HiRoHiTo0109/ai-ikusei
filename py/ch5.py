    "        self.blocks = nn.TransformerEncoder(layer, num_layers=2,\n"
    "                                            enable_nested_tensor=False)   # アテンション（Lv31）を2段\n"
    "        self.out = nn.Linear(dim, n_vocab)        # 次に来る文字それぞれの点数\n\n"
