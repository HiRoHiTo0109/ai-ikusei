LM_HEAD = (
    "import numpy as np\n\n"
    "rng = np.random.default_rng(0)\n"
    "C = 2        # 直前の何文字を見て、次を当てるか\n"
    "DIM = 16     # 1文字を何個の数字で表すか（Lv30 の埋め込み）\n\n"
    "def init(n_vocab):\n"
    "    return {\"E\": rng.normal(0, 0.3, (n_vocab, DIM)),          # 文字の地図（埋め込み）\n"
    "            \"W1\": rng.normal(0, 0.2, (DIM * C, 96)), \"b1\": np.zeros(96),\n"
    "            \"W2\": rng.normal(0, 0.2, (96, n_vocab)), \"b2\": np.zeros(n_vocab)}\n\n"
    "def forward(P, ctx):\n"
    "    # ctx: [問題の数, C]  直前C文字の番号 → 次の文字の確率\n"
    "    e = P[\"E\"][ctx].reshape(len(ctx), -1)     # 文字を地図の場所に変えて、横に並べる\n"
    "    h = np.tanh(e @ P[\"W1\"] + P[\"b1\"])       # 中間の細胞\n"
    "    z = h @ P[\"W2\"] + P[\"b2\"]\n"
    "    p = np.exp(z - z.max(axis=1, keepdims=True))\n"
    "    p /= p.sum(axis=1, keepdims=True)          # softmax：次の文字それぞれの確率\n"
    "    return e, h, p\n\n"
    "def grads(P, ctx, nxt):\n"
    "    # 逆伝播：全部の重みの傾きを計算する（用意済み）\n"
    "    e, h, p = forward(P, ctx)\n"
    "    d = p.copy(); d[np.arange(len(nxt)), nxt] -= 1; d /= len(nxt)\n"
    "    G = {\"W2\": h.T @ d, \"b2\": d.sum(axis=0)}\n"
    "    dh = (d @ P[\"W2\"].T) * (1 - h ** 2)\n"
    "    G[\"W1\"] = e.T @ dh; G[\"b1\"] = dh.sum(axis=0)\n"
    "    G[\"E\"] = np.zeros_like(P[\"E\"])\n"
    "    np.add.at(G[\"E\"], ctx, (dh @ P[\"W1\"].T).reshape(len(ctx), C, DIM))\n"
    "    return G\n\n"
    "def train(ids, n_vocab):\n"
    "    # ids: セリフ集を番号にした並び\n"
    "    ctx = np.array([ids[i:i + C] for i in range(len(ids) - C)])   # 問題：直前C文字\n"
    "    nxt = np.array(ids[C:])                                       # 正解：その次の文字\n"
    "    P = init(n_vocab)\n"
    "    for step in range(800):\n"
    "        G = grads(P, ctx, nxt)\n"
)
LM_MID = (
    "    return P\n\n"
    "def generate(P, start, n):\n"
    "    # start: 書き出し（C文字ぶんの番号のリスト）。続きを n 文字書く\n"
    "    out = list(start)\n"
    "    for _ in range(n):\n"
    "        e, h, p = forward(P, np.array([out[-C:]]))   # 直近C文字を見る\n"
    "        probs = p[0]                                  # 次の文字の確率\n"
)

